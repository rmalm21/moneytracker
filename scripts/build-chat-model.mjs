/**
 * Trains the chat intent model once, at build time (the app never trains on the device):
 * node scripts/build-chat-model.mjs → lib/chat/chat-model.ts. Corpus: lib/chat/corpus.ts, each sentence with its everyday
 * variants (lib/chat/corpus.ts augment).
 */
import { writeFileSync } from 'node:fs';
import { containerBootstrap } from '@nlpjs/core';
import { Nlp } from '@nlpjs/nlp';
import { LangId } from '@nlpjs/lang-id';
import { CHAT_CORPUS, augment, chatFeature } from '../lib/chat/corpus.ts';

const container = await containerBootstrap();
container.use(Nlp); container.use(LangId);
const nlp = container.get('nlp');
nlp.settings.autoSave = false; nlp.settings.nlu = { log: false };
nlp.addLanguage('id');
let n = 0;
let base = 0;
for (const [intent, list] of Object.entries(CHAT_CORPUS)) for (const s of list) { base++; for (const v of augment(s)) { nlp.addDocument('id', chatFeature(v), intent); n++; } }
const t0 = Date.now();
await nlp.train();
const model = nlp.export(true);
writeFileSync(new URL('../lib/chat/chat-model.ts', import.meta.url), `/** Generated by scripts/build-chat-model.mjs — the serialized NLP.js chat intent model (do not edit). */\nexport default ${JSON.stringify(model)};\n`);
console.log(`Chat model: ${base} sentences (${n} with variants), trained in ${Date.now() - t0} ms, ${(model.length / 1024).toFixed(1)} KB`);
